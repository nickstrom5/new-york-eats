"""The state outline for the app header and the website: mainland New York and Long Island (Kings, Queens, Nassau and Suffolk counties,
the island itself), simplified from the Census county outlines and normalized to a unit box.
Writes NewYorkEats/Design/StateOutline.swift and playbook/state-outline.json (the website's generator reads the JSON).
Usage: .venv/bin/python scripts/make-outline.py"""
import os, json
from shapely.geometry import shape, Polygon, MultiPolygon
from shapely.ops import unary_union

ROOT = os.path.join(os.path.dirname(__file__), "..")
feats = json.load(open(f"{ROOT}/data/ny/ny_counties.geojson"))["features"]
LI = {"Kings", "Queens", "Nassau", "Suffolk"}
li = unary_union([shape(f["geometry"]) for f in feats if f["properties"]["county"] in LI]).buffer(0.004).buffer(-0.004)
main = unary_union([shape(f["geometry"]) for f in feats if f["properties"]["county"] not in LI]).buffer(0.004).buffer(-0.004)


def biggest(g, n=1):
    polys = sorted(getattr(g, "geoms", [g]), key=lambda p: -p.area)
    return polys[:n]


li_poly = biggest(li)[0]                       # the island (not Fishers or Shelter Island)
main_polys = biggest(main, 2)                   # the mainland, plus Staten Island
minx, miny, maxx, maxy = unary_union([li_poly] + main_polys).bounds
w, h = (maxx - minx) * 0.74, (maxy - miny)      # longitude shrinks by cos(42.7°)


def ring(p, tol):
    q = p.simplify(tol, preserve_topology=True)
    return [[round((x - minx) * 0.74 / w, 4), round(1 - (y - miny) / h, 4)] for x, y in q.exterior.coords]


out = {"aspect": round(w / h, 4), "mainland": [ring(p, 0.02) for p in main_polys], "long_island": ring(li_poly, 0.012)}
json.dump(out, open(f"{ROOT}/playbook/state-outline.json", "w"))
fmt = lambda pts: "[" + ", ".join(f"({x}, {y})" for x, y in pts) + "]"
swift = f'''import SwiftUI

// Generated by scripts/make-outline.py from the Census county outlines (public domain). Don't edit by hand.

/// New York State's outline in a unit box (x right, y down), mainland and Long Island separately, for the one New York element in
/// the header: the state in blue with Long Island picked out in gold.
enum StateOutline {{
    static let aspect: CGFloat = {out["aspect"]}
    static let mainland: [[(CGFloat, CGFloat)]] = [{", ".join(fmt(r) for r in out["mainland"])}]
    static let longIsland: [(CGFloat, CGFloat)] = {fmt(out["long_island"])}
}}

struct StateShape: Shape {{
    var longIsland = false
    func path(in r: CGRect) -> Path {{
        // fit the unit box into r, keeping the state's proportions, aligned left
        let h = min(r.height, r.width / StateOutline.aspect), w = h * StateOutline.aspect
        var p = Path()
        for ring in longIsland ? [StateOutline.longIsland] : StateOutline.mainland {{
            guard let first = ring.first else {{ continue }}
            p.move(to: CGPoint(x: r.minX + first.0 * w, y: r.minY + first.1 * h))
            for pt in ring.dropFirst() {{ p.addLine(to: CGPoint(x: r.minX + pt.0 * w, y: r.minY + pt.1 * h)) }}
            p.closeSubpath()
        }}
        return p
    }}
}}
'''
open(f"{ROOT}/NewYorkEats/Design/StateOutline.swift", "w").write(swift)
print("aspect", out["aspect"], "| points:", sum(len(r) for r in out["mainland"]), "+", len(out["long_island"]))
